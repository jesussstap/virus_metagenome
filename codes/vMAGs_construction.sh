#!/bin/bash
# ========================================================
# vRhyme Pipeline (Mapping + Binning + CheckV)
# ========================================================
# You must have CheckV and vRHyme installed to run this code  

# ========================================================
# PATH CONFIGURATION (Modify per your environment or use variables)
# ========================================================
BASE_DIR="${BASE_DIR:-.}"
UNIQUE_FASTA="${UNIQUE_FASTA:-$BASE_DIR/data/viral_catalog.fasta}"
READS_DIR="${READS_DIR:-$BASE_DIR/reads_trimmed}"
OUT_DIR="${OUT_DIR:-$BASE_DIR/vrhyme}"
VRHYME_OUT="$OUT_DIR/vRhyme_FINAL"

# Auxiliary script paths and external databases
LINK_SCRIPT="${LINK_SCRIPT:-link_bin_sequences.py}" #file supplied by vRhyme
CHECKV_DB="${CHECKV_DB:-$HOME/checkv/checkv_db}"

echo "========================================================"
echo "Starting Local vRhyme Pipeline (Mapping + Binning)"
echo "Base directory: $BASE_DIR"
echo "========================================================"

# Create output directory
mkdir -p "$OUT_DIR"

# Clear old BAMs folder to force new mapping if needed
rm -rf "$OUT_DIR/bams"
mkdir -p "$OUT_DIR/bams"

# Verify that the viral catalog exists
if [ ! -f "$UNIQUE_FASTA" ]; then
    echo "[ERROR] Viral catalog not found at: $UNIQUE_FASTA"
    exit 1
fi

unique_total=$(grep -c "^>" "$UNIQUE_FASTA")
echo "-> Viral catalog loaded successfully. Contains $unique_total unique vOTUs."

# 1. MASSIVE MAPPING (Coverage profiling)
echo "-> [1/3] Starting sample mapping..."

for R1 in "$READS_DIR"/*_R1.fastq.gz; do
    if [ ! -e "$R1" ]; then
        echo "[ERROR] No FASTQ files found in $READS_DIR"
        exit 1
    fi
    
    nombre_archivo=$(basename "$R1")
    sample=${nombre_archivo%_R1.fastq.gz}
    R2="${READS_DIR}/${sample}_R2.fastq.gz"
    
    if [[ -f "$R1" && -f "$R2" ]]; then
        if [[ ! -f "$OUT_DIR/bams/${sample}.sorted.bam" ]]; then
            echo "   + Mapping sample: $sample"
            
            minimap2 -t 8 -ax sr "$UNIQUE_FASTA" "$R1" "$R2" | \
            samtools view -@ 4 -bS - | \
            samtools sort -@ 4 -o "$OUT_DIR/bams/${sample}.sorted.bam"
            
            samtools index "$OUT_DIR/bams/${sample}.sorted.bam"
        else
            echo "   + BAM already exists for $sample. Skipping mapping..."
        fi
    else
        echo "   [!] Warning: R2 pair not found for $sample. Skipping..."
    fi
done

# 2. RUN VRHYME
echo "-> [2/3] Running vRhyme (Binning)..."
rm -rf "$VRHYME_OUT"

vRhyme -i "$UNIQUE_FASTA" \
       -b "$OUT_DIR/bams"/*.sorted.bam \
       -o "$VRHYME_OUT" 
       
# 3. PREPARE BINS FOR CHECKV
echo "-> Linking bin sequences..."
LINKED_DIR="$VRHYME_OUT/vMAGs_for_checkv"
rm -rf "$LINKED_DIR"

python3 "$LINK_SCRIPT" \
    -i "$VRHYME_OUT/vRhyme_best_bins_fasta" \
    -e fasta \
    -o "$LINKED_DIR"
    
# Consolidate results
cd "$LINKED_DIR"
if ls *.fasta 1> /dev/null 2>&1; then
    cat *.fasta > ../consolidated_vMAGs.fasta
else
    echo "[CRITICAL ERROR] No bins generated by vRhyme. Check vRhyme logs."
    exit 1
fi
cd - > /dev/null

# 4. RUN CHECKV
echo "-> [3/3] Starting CheckV evaluation..."

CHECKV_OUT="$BASE_DIR/checkv_bins_output"
rm -rf "$CHECKV_OUT"

checkv end_to_end "$VRHYME_OUT/consolidated_vMAGs.fasta" "$CHECKV_OUT" -d "$CHECKV_DB"

echo "========================================================"
echo "Finished!!"
echo "CheckV results in: $CHECKV_OUT"
echo "========================================================"
